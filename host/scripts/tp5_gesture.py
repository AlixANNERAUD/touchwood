"""TP 5, part 2 (the "Colab" side): produce the gesture model and the fixed test windows for the
`firmware/gesture` crate, and print the reference probabilities to compare with the board.

Two modes:

* Real TP 2 files (what the TP asks for):
      uv run python scripts/tp5_gesture.py --tflite model_int8.tflite --test-windows test_windows.h
  `test_windows.h` is the file generated by the TP's Colab code (section 2.2).
* No files: a stand-in model is trained on synthetic accelerometer gestures, to test the whole
  chain (export -> Rust firmware -> nanoglia on the board):
      uv run python scripts/tp5_gesture.py

Outputs (in `firmware/gesture/`): `models/gesture_model.tflite` (the model, embedded by the
firmware with `include_bytes!` instead of a `gesture_model.h` C array) and `src/test_windows.rs`
(the equivalent of `test_windows.h`).

Pre-processing assumed, as in the TP: 100 Hz, raw acceleration in g, WINDOW samples, flattened
interleaved (x0, y0, z0, x1, ...). Classes: idle, up_down, side, forward.
"""

import argparse
import re
import warnings
from pathlib import Path

import numpy as np
import tensorflow as tf

from touchwood.export import to_int8_tflite

FIRMWARE = Path(__file__).resolve().parents[2] / "firmware" / "gesture"
CLASSES = ["idle", "up_down", "side", "forward"]
WINDOW = 50
N_AXES = 3
RATE_HZ = 100


def synthetic_gestures(n_per_class: int, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """Windows of (WINDOW, 3) accelerations in g, board lying flat (gravity on +z).

    idle: gravity + noise; up_down: oscillation on z; side: on x; forward: on y.
    Amplitude, frequency, phase, tilt and offset vary, so the model has to generalise a little.
    """
    t = np.arange(WINDOW) / RATE_HZ
    xs, ys = [], []
    for c in range(len(CLASSES)):
        for _ in range(n_per_class):
            w = np.zeros((WINDOW, N_AXES))
            w[:, 2] = 1.0  # gravity
            w += rng.normal(0, 0.15, size=3)  # tilt / calibration offset
            w += rng.normal(0, 0.03, size=w.shape)  # sensor noise
            if c > 0:
                axis = {1: 2, 2: 0, 3: 1}[c]
                amp = rng.uniform(0.4, 1.5)
                freq = rng.uniform(1.0, 3.0)
                w[:, axis] += amp * np.sin(2 * np.pi * freq * t + rng.uniform(0, 2 * np.pi))
            xs.append(w.reshape(-1))  # interleaved: x0, y0, z0, x1, ...
            ys.append(c)
    return np.asarray(xs, dtype=np.float32), np.asarray(ys)


def train_stand_in() -> tuple[bytes, np.ndarray, np.ndarray]:
    rng = np.random.default_rng(0)
    tf.keras.utils.set_random_seed(0)
    x_train, y_train = synthetic_gestures(400, rng)
    x_test, y_test = synthetic_gestures(50, rng)
    def build(batch_size: int | None) -> tf.keras.Model:
        return tf.keras.Sequential(
            [
                tf.keras.Input((WINDOW * N_AXES,), batch_size=batch_size),
                tf.keras.layers.Dense(32, activation="relu"),
                tf.keras.layers.Dense(16, activation="relu"),
                tf.keras.layers.Dense(len(CLASSES), activation="softmax"),
            ]
        )

    train = build(None)
    train.compile("adam", "sparse_categorical_crossentropy", metrics=["accuracy"])
    train.fit(x_train, y_train, epochs=20, batch_size=32, verbose=0)
    print(f"stand-in model: float test accuracy {train.evaluate(x_test, y_test, verbose=0)[1]:.3f}")
    # Static batch size of 1 for the export (see touchwood.model.for_export).
    model = build(1)
    model.set_weights(train.get_weights())
    return to_int8_tflite(model, x_train[:200]), x_test, y_test


def parse_test_windows_h(path: Path) -> tuple[np.ndarray, np.ndarray]:
    """Read the `test_labels` and `test_windows` arrays of the TP's test_windows.h."""
    text = path.read_text()
    labels = re.search(r"test_labels\[[^\]]*\]\s*=\s*\{([^}]*)\}", text)
    body = re.search(r"test_windows\[[^\]]*\]\[(\d+)\]\s*=\s*\{(.*)\};", text, re.S)
    if not labels or not body:
        raise ValueError(f"{path}: test_labels / test_windows not found")
    n_inputs = int(body.group(1))
    values = [float(v) for v in re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", body.group(2))]
    return np.asarray(values, dtype=np.float32).reshape(-1, n_inputs), np.asarray(
        [int(v) for v in labels.group(1).split(",")]
    )


def reference_probs(tflite: bytes, windows: np.ndarray) -> np.ndarray:
    """Same computation as the TP's Colab code: quantize, run, dequantize (one window at a time)."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # tf.lite.Interpreter deprecation notice
        interp = tf.lite.Interpreter(model_content=tflite)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    print("input:", inp["shape"], inp["dtype"].__name__, "output:", out["shape"], out["dtype"].__name__)
    s, z = inp["quantization"]
    s_o, z_o = out["quantization"]
    probs = []
    for w in windows:
        x = w if s == 0 else np.clip(np.round(w / s + z), -128, 127)
        interp.set_tensor(inp["index"], x.astype(inp["dtype"]).reshape(inp["shape"]))
        interp.invoke()
        raw = interp.get_tensor(out["index"]).astype(np.float32).reshape(-1)
        probs.append(raw if s_o == 0 else (raw - z_o) * s_o)
    return np.asarray(probs)


def write_test_windows_rs(path: Path, windows: np.ndarray, labels: np.ndarray) -> None:
    rows = ",\n".join("    [" + ", ".join(f"{v:.6}" for v in w) + "]" for w in windows)
    path.write_text(
        "// Generated by host/scripts/tp5_gesture.py: one pre-processed window per class (the\n"
        "// TP's test_windows.h). Do not edit by hand.\n\n"
        f"pub const N_TEST: usize = {len(windows)};\n"
        f"pub const TEST_LABELS: [usize; N_TEST] = [{', '.join(str(int(c)) for c in labels)}];\n"
        f"pub static TEST_WINDOWS: [[f32; {windows.shape[1]}]; N_TEST] = [\n{rows},\n];\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tflite", type=Path, help="model chosen at TP 2 (default: train a stand-in)")
    ap.add_argument("--test-windows", type=Path, help="test_windows.h from the TP's Colab code")
    args = ap.parse_args()

    if args.tflite:
        tflite = args.tflite.read_bytes()
        if not args.test_windows:
            ap.error("--tflite needs --test-windows (the windows must match the model's pre-processing)")
        windows, labels = parse_test_windows_h(args.test_windows)
    else:
        tflite, x_test, y_test = train_stand_in()
        if args.test_windows:
            windows, labels = parse_test_windows_h(args.test_windows)
        else:
            idx = [int(np.where(y_test == c)[0][0]) for c in range(len(CLASSES))]
            windows, labels = x_test[idx], y_test[idx]
        int8 = reference_probs(tflite, x_test).argmax(axis=1)
        print(f"stand-in model: int8 test accuracy {(int8 == y_test).mean():.3f}")

    (FIRMWARE / "models").mkdir(parents=True, exist_ok=True)
    (FIRMWARE / "models" / "gesture_model.tflite").write_bytes(tflite)
    write_test_windows_rs(FIRMWARE / "src" / "test_windows.rs", windows, labels)
    print(f"gesture_model.tflite: {len(tflite)} bytes, test windows: labels {labels.tolist()}")

    probs = reference_probs(tflite, windows)
    print("reference probabilities (one line per window, compare with the board):")
    for k, (p, c) in enumerate(zip(probs, labels)):
        print(f"  window {k} | expected: {CLASSES[c]:8} | " + " ".join(f"{v:.3f}" for v in p))


if __name__ == "__main__":
    main()
